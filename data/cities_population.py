def get_population(city_name: str) -> int:
    """
    Возвращает население города в тыс. человек.
    Нормализует название: убирает префиксы г., г, пгт, рп, п, с, д, х и т.д.
    """
    if not city_name:
        return 0

    name = str(city_name).lower().strip()

    # убираем типовые префиксы
    prefixes = [
        'г. ', 'г.', 'город ', 'г ', 'пгт ', 'пгт. ', 'рп ', 'рп. ',
        'п. ', 'п ', 'с. ', 'с ', 'д. ', 'д ', 'х. ', 'х ', 'аг ',
        'мкр ', 'мкр. ', 'ст. ', 'ст ', 'пос. ', 'пос ', 'гп ',
        'нп ', 'нп. ', 'кп ', 'кп. ',
    ]
    for p in prefixes:
        if name.startswith(p):
            name = name[len(p):].strip()
            break

    # убираем скобки с регионом типа "саров (нижегородская обл)"
    if '(' in name:
        name = name[:name.index('(')].strip()

    # убираем лишние точки и дефисы в конце
    name = name.rstrip('.-').strip()

    return CITIES_POPULATION.get(name, 0)


def get_population_segment(city_name: str) -> str:
    """
    Возвращает сегмент населённого пункта по численности населения.
    """
    pop = get_population(city_name)

    if pop == 0:
        return "до 20 тыс."      # неизвестные — сёла/деревни/малые нп
    elif pop < 20:
        return "до 20 тыс."
    elif pop < 50:
        return "20–50 тыс."
    elif pop < 100:
        return "50–100 тыс."
    else:
        return "100 тыс.+"


